#!/usr/bin/env bash
# Package zesignal and install it where Zenie finds it:
#   ~/.local/share/zesignal/   the packaged app
#   ~/.local/bin/zesignal      launcher (MCP server on)
#
#   utility/install.sh              build, package, install
#   utility/install.sh --uninstall  remove the app (keeps your data)
set -euo pipefail
source "$(dirname "${BASH_SOURCE[0]}")/common.sh"

if [[ "${1:-}" == --uninstall ]]; then
  rm -rf "$INSTALL_DIR" "$BIN_DIR/zesignal"
  say "Removed. Your messages stay in $USER_DATA"
  exit 0
fi
[[ -z "${1:-}" ]] || die "unknown option: $1"

setup_toolchain

say "Building"
in_node 'pnpm run generate'
# Packaged builds read only default, production and local-production.json;
# the last is regenerated by `generate`, so the overrides go in after it.
local_config=config/local-production.json
[[ -f "$local_config" ]] || die "$local_config missing after generate"
sed -i "s/}\s*$/,$CONFIG_OVERRIDES}/" "$local_config"

build_panel

say "Packaging (unpacked Linux directory)"
rm -rf release/linux-unpacked
in_node 'SIGNAL_ENV=production pnpm run build:electron --linux dir --config.directories.output=release'
[[ -x release/linux-unpacked/signal-desktop ]] || die "packaging produced no release/linux-unpacked/signal-desktop"

say "Installing to $INSTALL_DIR"
rm -rf "$INSTALL_DIR.new"
cp -a release/linux-unpacked "$INSTALL_DIR.new"
# The panel sits beside app.asar; app/zechat_link.main.ts loads it from there.
cp -a zechat-panel/dist "$INSTALL_DIR.new/resources/zechat-panel"
rm -rf "$INSTALL_DIR"
mv "$INSTALL_DIR.new" "$INSTALL_DIR"

mkdir -p "$BIN_DIR"
cat > "$BIN_DIR/zesignal" <<EOF
#!/bin/sh
# zesignal launcher, written by $ROOT/utility/install.sh
export ZESIGNAL_MCP=1 ZESIGNAL_MCP_PORT=$PORT
exec "$INSTALL_DIR/signal-desktop" "\$@"
EOF
chmod 755 "$BIN_DIR/zesignal"

setup_sandbox

say "Installed: run 'zesignal' or open it from the Zenie launcher"
[[ -f "$USER_DATA/mcp.json" ]] || say "First run: link your phone, then run: utility/run.sh --config"
