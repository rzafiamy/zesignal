// Brings in the ZeChat client this panel is.
//
// Like zechat-chrome's side panel, the panel is zechat-client with one plugin
// registered (src/signal): its whole `src/` is copied to `src/client/` and its
// page to `panel.html`. Edit the client in zechat-client, never here. The one
// difference from Chrome: the client reaches ZeChat over its local link, not a
// hub (src/link-hub.js, swapped in for lib/hub.js by vite.config.js).
//
// zechat-client is proprietary: what this copies is gitignored and must stay
// out of this public repository. utility/*.sh run this before every build.
import { cpSync, existsSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const client =
  process.env.ZECHAT_CLIENT_REPO || resolve(root, "../../../zechat-client");

if (!existsSync(join(client, "src/main.js"))) {
  if (existsSync(join(root, "src/client/main.js"))) {
    console.warn(`zechat-client not found at ${client}: building with the copy already here`);
    process.exit(0);
  }
  console.error(`zechat-client not found at ${client}: it is required to build the panel. Set ZECHAT_CLIENT_REPO to your checkout.`);
  process.exit(1);
}

rmSync(join(root, "src/client"), { recursive: true, force: true });
cpSync(join(client, "src"), join(root, "src/client"), { recursive: true });
console.log("zechat-client/src → src/client");

// main.js reads the client's version from its package.json, one level up
// from src/; here that is two.
const mainPath = join(root, "src/client/main.js");
writeFileSync(
  mainPath,
  readFileSync(mainPath, "utf8").replace('from "../package.json"', 'from "../../package.json"')
);

// Tailwind skips gitignored files when it looks for classes, and the copy is
// gitignored: name it explicitly, or the client's utilities vanish from the CSS.
const stylesPath = join(root, "src/client/styles.css");
const styles = readFileSync(stylesPath, "utf8");
if (!/@import\s+["']tailwindcss["'][^;]*;/.test(styles)) {
  console.error("src/client/styles.css no longer imports tailwindcss: update scripts/sync-client.mjs");
  process.exit(1);
}
writeFileSync(
  stylesPath,
  styles.replace(/@import\s+["']tailwindcss["'][^;]*;/, (line) => `${line}\n@source "./";\n@source "../../panel.html";`)
);

for (const dir of ["icons"]) {
  if (existsSync(join(client, "public", dir))) {
    rmSync(join(root, "public", dir), { recursive: true, force: true });
    cpSync(join(client, "public", dir), join(root, "public", dir), { recursive: true });
  }
}

writeFileSync(join(root, "panel.html"), panelPage(readFileSync(join(client, "index.html"), "utf8")));
console.log("zechat-client/index.html → panel.html");

function panelPage(html) {
  return `<!-- Generated by \`npm run update:client\` from zechat-client/index.html — do not edit. -->\n${html}`
    .replace('href="./src/styles.css"', 'href="./src/client/styles.css"')
    .replace('src="./src/main.js"', 'src="./src/panel.js"')
    .replace(/\s*<link rel="manifest"[^>]*>/g, "")
    .replace(/\s*<meta name="(theme-color|apple-mobile-web-app-[^"]+)"[^>]*>/g, "")
    .replace(/\s*<link rel="apple-touch-icon"[^>]*>/g, "");
}
